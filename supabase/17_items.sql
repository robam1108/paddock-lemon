--  02_schema.sql 이 만들고, 행은 전부 여기서 채운다 — 예전에는 02 에도
--  부트스트랩 사본이 있었는데, 두 곳이 어긋나면 02 를 다시 돌리는 순간
--  카탈로그가 조용히 옛 값으로 되감겨서 지웠다.
--
--  적용 순서는 17 번이다(supabase/APPLY.md). 11_item_uses.sql 이 만든 uses 와
--  16_steal_trick.sql 이 만든 steal_sure · flex_text_stolen 컬럼을 채우므로
--  그 뒤에 와야 하고, 18_labor.sql · 19_search.sql 이 여기 있는 아이템 코드를
