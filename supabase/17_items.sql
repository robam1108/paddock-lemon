--
--  안전성:
--    · insert ... on conflict (code) do update 라서 몇 번을 다시 돌려도
--      안전하다(멱등). 새 code 는 추가되고, 기존 code 는 값만 갱신된다.
--    · public.inventories 는 item_code 만 들고 있고 이름/설명을 복사해
--      두지 않는다(02_schema.sql 참고). 그래서 여기서 설명을 고쳐도 이미
--      물건을 가지고 있는 유저의 가방·거래·밀거래 내역이 전혀 깨지지
--      않는다 — 다음에 화면을 열 때 바로 새 설명으로 보인다.
--    · buy_price 를 null 로 두면 배급소(app.roll_shop)·밀거래 상시분
--      (app.roll_smuggle)·특별 상품(app.roll_special) 어느 추첨에도
--      걸리지 않는다. 반대로 buy_price 를 채우고 kind 를
--      'food'/'medicine' 가 아닌 것으로 두면 자동으로 밀거래 추첨 풀에
--      들어간다 — 밀거래 전용 목록은 따로 없다.
--    · 이 파일은 오직 item_defs 한 테이블만 건드린다. 테이블 구조나
--      제약조건, 다른 함수는 손대지 않으므로 락도 다운타임도 없다.
--    · 파일 끝의 "개비 수(uses)" 표는 item_defs.uses 컬럼을 쓴다 — 이
--      컬럼은 11_item_uses.sql(또는 02_schema.sql)이 먼저 만들어 둬야
--      한다. 아직 없는 상태에서 이 파일을 돌리면 그 부분만 에러가 난다.
--    · 마찬가지로 절도비법(steal_trick) 행과 "훔친 문구(flex_text_stolen)"
--      표는 item_defs.flex_text_stolen / steal_sure 컬럼을 쓴다 — 이 컬럼은
--      16_steal_trick.sql(또는 02_schema.sql)이 먼저 만들어 둬야 한다.
--
--  배포 순서: 클라이언트(ITEM_KIND_LABEL·ItemMark 갱신분) 먼저 → 이 SQL
--  나중. 순서를 뒤집으면 예전 화면을 띄워둔 유저가 새 갈래 자리에 영문
