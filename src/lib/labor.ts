export type SearchTier =
  | "miss"
  | "ration"
  | "junk"
  | "plain"
  | "good"
  | "prize"
  | "legend";

/**
 * 무엇이 나왔는지가 아니라 얼마나 대단한 걸 건졌는지가 문장을 가른다.
 * 등급을 축으로 삼고(탐험 추첨 자체가 등급을 먼저 뽑는 구조라 등급이 곧
 * 희소성이다), **일반 등급만** buy_price 로 한 번 더 가른다 — 값싼 물건과
 * 라이터(60)가 같은 등급이라고 같은 문장을 쓰면 안 된다.
 *
 * 고급(uncommon)은 항상 plain 이다. 한 장소의 common+uncommon 풀이 죄다
 * 50코인 밑이면, 가격 경계를 두 등급 모두에 걸었을 때 그 장소의 결과가
 * 거의 다 junk 로 쏠린다. 가격 분기를 common 안으로만 좁혀서
 * "등급이 오르면 문장도 오른다"는 원칙을 지킨다.
 *
 * miss/ration 은 결과 전체(SearchResult)를 보고 먼저 갈라야 한다 — 등급
 * 필드는 꽝일 때 아예 없고, 간식(ration)은 등급 개념 밖의 전용 아이템이다.
 */
export function searchTier(r: SearchResult): SearchTier {
  if (r.miss || !r.item) return "miss";
  if (r.ration) return "ration";
  if (r.item.grade === "legendary") return "legend";
  if (r.item.grade === "epic") return "prize";
  if (r.item.grade === "rare") return "good";
  if (r.item.grade === "uncommon") return "plain";
  return (r.item.buy_price ?? 0) >= 50 ? "plain" : "junk";
}

